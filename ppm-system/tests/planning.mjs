import assert from 'node:assert/strict';
import vm from 'node:vm';
import {readFileSync} from 'node:fs';
const context=vm.createContext({Intl,Date});
vm.runInContext(readFileSync(new URL('../workflow.js',import.meta.url),'utf8'),context);
const dates=(...args)=>JSON.parse(JSON.stringify(context.contractDates(...args)));
assert.deepEqual(dates('2026-01-31','2026-04-30',1),['2026-01-31','2026-02-28','2026-03-31','2026-04-30']);
assert.deepEqual(dates('2028-01-31','2028-03-31',1),['2028-01-31','2028-02-29','2028-03-31']);
assert.deepEqual(dates('2028-02-29','2030-02-28',12),['2028-02-29','2029-02-28','2030-02-28']);
assert.deepEqual(dates('2026-01-31','2026-10-31',3),['2026-01-31','2026-04-30','2026-07-31','2026-10-31']);
assert.equal(dates('2026-01-01','2040-01-01',1).length,0,'Do not silently truncate long contracts');
assert.equal(dates('2027-01-01','2026-01-01',1).length,0);
context.Date=class extends Date{constructor(...args){super(...(args.length?args:['2026-10-10T22:30:00Z']));}};
assert.equal(context.todayISO(),'2026-10-11','Riyadh day boundary');
assert.equal(context.scheduleState({due_date:'2026-10-10',visits:[]}).label,'متأخرة');
assert.equal(context.scheduleState({due_date:'2026-10-11',visits:[]}).label,'مستحقة اليوم');
assert.equal(context.scheduleState({due_date:'2026-10-10',visits:[{status:'draft'}]}).label,'قيد التنفيذ');
console.log('PASS monthly, quarterly and yearly planning, leap years, bounds and Riyadh due-date states');
context.me={id:'second',role:'technician'};
assert.equal(context.scheduledForMe({technician_id:'lead',scheduled_visit_technicians:[{technician_id:'lead'},{technician_id:'second'}]}),true);
assert.equal(context.scheduledForMe({technician_id:'lead',scheduled_visit_technicians:[{technician_id:'lead'}]}),false);
assert.equal(context.scheduleState({due_date:'2026-10-01',completed_externally_on:'2026-10-05',visits:[]}).label,'منفّذة سابقًا');
console.log('PASS shared assignment visibility and historical completion state');
const range=(...args)=>JSON.parse(JSON.stringify(context.scheduleDateRange(...args)));
assert.deepEqual(range('month','2028-02','2026-10-10'),{start:'2028-02-01',end:'2028-02-29'});
assert.deepEqual(range('month','2026-12','2026-10-10'),{start:'2026-12-01',end:'2026-12-31'});
assert.deepEqual(range('month','','2026-10-10'),{start:'2026-10-01',end:'2026-10-31'});
assert.deepEqual(range('next14','', '2026-12-25'),{start:'2026-12-25',end:'2027-01-07'});
assert.deepEqual(range('past14','', '2026-01-05'),{start:'2025-12-22',end:'2026-01-04'});
assert.equal(range('all','','2026-10-10'),null);
console.log('PASS calendar-month and two-week windows across leap years and year boundaries');
