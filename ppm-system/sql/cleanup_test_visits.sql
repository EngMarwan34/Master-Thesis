-- =====================================================================
-- تنظيف الزيارات التجريبية القديمة (ليست ترقية، شغّلها مرة واحدة يدوياً)
-- =====================================================================

-- الخطوة ١: شغّل هذا أولاً لمراجعة كل الزيارات المفتوحة حالياً (قيد
-- التنفيذ أو أُعيدت للتعديل) مع اسم العميل والفني وتاريخها
select v.id, v.visit_type, v.status, v.visit_date, v.check_in,
       c.name_ar as client_name, p.full_name as technician_name
from visits v
join clients c on c.id = v.client_id
left join profiles p on p.id = v.technician_id
where v.status in ('draft','rejected')
order by v.check_in desc;

